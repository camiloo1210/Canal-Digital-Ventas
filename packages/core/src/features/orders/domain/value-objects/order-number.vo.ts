/**
 * Public order reference ("ORD-K7M3-9QXD-4TWB").
 *
 * Twelve symbols from a 32-letter alphabet are 60 random bits: unique per store for all practical
 * purposes and impossible to guess, so the number alone can be used to look an order up. The
 * alphabet drops I, L, O and U so it survives being read aloud or retyped.
 */
const ALPHABET = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
const SYMBOLS = 12;
const GROUP = 4;

/** Normalized form of an unguessable reference: no separators, lower case. */
const UNGUESSABLE = /^ord[0-9a-hjkmnp-tv-z]{12}$/;

/** Generates a new reference. `random` is injectable for tests; defaults to Web Crypto. */
export function generateOrderNumber(
  random: (length: number) => Uint8Array = (length: number): Uint8Array =>
    crypto.getRandomValues(new Uint8Array(length)),
): string {
  const bytes = random(SYMBOLS);
  let symbols = '';
  // 256 is a multiple of 32, so masking five bits adds no modulo bias.
  for (let index = 0; index < SYMBOLS; index++) symbols += ALPHABET[bytes[index] & 31];
  const groups: string[] = [];
  for (let index = 0; index < SYMBOLS; index += GROUP)
    groups.push(symbols.slice(index, index + GROUP));
  return `ORD-${groups.join('-')}`;
}

/** Strips what a person may add or drop when typing a reference: #, spaces and dashes. */
export function normalizeOrderNumber(value: string): string {
  return value.replace(/[#\s-]/g, '').toLowerCase();
}

/** True for references generated by {@link generateOrderNumber}; older numbers are guessable. */
export function isUnguessableOrderNumber(value: string): boolean {
  return UNGUESSABLE.test(normalizeOrderNumber(value));
}
